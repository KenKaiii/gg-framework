#!/usr/bin/env python3
"""Bake m5x7 (CC0, Daniel Linssen) into src/pixel-font-m5x7.ts.

The Goal world draws its text onto a small pixel canvas that CSS scales up,
so it needs the font as real pixels: each glyph rasterised once at the font's
native 16px, thresholded, and stored as rows of "#" and ".". That keeps the
text crisp, sync (no font loading) and measurable in tests.

    python3 scripts/gen-pixel-font.py   (needs Pillow; run from gg-app/)
"""
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "src/assets/fonts/m5x7/m5x7.ttf"
OUT = ROOT / "src/pixel-font-m5x7.ts"

font = ImageFont.truetype(str(FONT), 16)
chars = [chr(c) for c in range(33, 127)] + ["é", "è", "á", "à", "ü", "ö", "ñ"]

# Render each glyph on a tall canvas with the baseline at a fixed row, so all
# glyphs share one band.
BASE = 20
glyphs = {}
for ch in chars:
    img = Image.new("L", (24, 32), 0)
    ImageDraw.Draw(img).text((0, BASE), ch, font=font, fill=255, anchor="ls")
    on = [[img.getpixel((x, y)) > 110 for x in range(24)] for y in range(32)]
    glyphs[ch] = (on, round(font.getlength(ch)))

rows_on = [y for on, _ in glyphs.values() for y in range(32) if any(on[y])]
top, bottom = min(rows_on), max(rows_on)
height = bottom - top + 1
baseline = BASE - top

lines = []
for ch, (on, adv) in glyphs.items():
    ink = max((x for y in range(32) for x in range(24) if on[y][x]), default=-1)
    w = max(ink + 1, 1)
    rows = ["".join("#" if on[y][x] else "." for x in range(w)) for y in range(top, bottom + 1)]
    lines.append(f"  {json.dumps(ch, ensure_ascii=False)}: {{ advance: {adv}, rows: {json.dumps(rows)} }},")

body = "\n".join(lines)
src = f"""// Generated by scripts/gen-pixel-font.py from m5x7 by Daniel Linssen (CC0).
// Do not edit by hand: change the script and run it again.

export interface PixelGlyph {{
  /** Pixels to the next glyph's left edge (the 1px letter gap included). */
  readonly advance: number;
  /** One string per row, top to bottom; "#" is ink. */
  readonly rows: readonly string[];
}}

/** Rows in every glyph: ascenders to descenders. */
export const M5X7_HEIGHT = {height};
/** Row of the baseline, counted from the top of the band. */
export const M5X7_BASELINE = {baseline};
/** Width of a space. */
export const M5X7_SPACE = {round(font.getlength(" "))};

export const M5X7: Readonly<Record<string, PixelGlyph>> = {{
{body}
}};
"""
OUT.write_text(src)
print(f"wrote {OUT.relative_to(ROOT)}: {len(glyphs)} glyphs, height {height}, baseline {baseline}")
